"""Generate pow/game/ae.py from ae.java (the constants interface) mechanically.

Usage: python pyport/tools/gen_ae.py
Each Java `public static final T[] NAME = new T[] { ... };` becomes `NAME = [...]`
with a `# ae.java:LINE` comment. Nothing is hand-edited, so the table stays 1:1 with Java.
"""
import pathlib
import keyword
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "ae.java"
DST = ROOT / "pyport" / "pow" / "game" / "ae.py"

DECL = re.compile(r"public static final ([\w\[\]]+) (\w+) = (?:new [\w\[\]]+ )?")


def convert(body: str) -> str:
    out = []
    in_str = False
    for ch in body:
        if ch == '"':
            in_str = not in_str
        if not in_str and ch == "{":
            out.append("[")
        elif not in_str and ch == "}":
            out.append("]")
        else:
            out.append(ch)
    return "".join(out)


def main():
    text = SRC.read_text(encoding="utf-8")
    lines = text.splitlines()
    res = ['"""ae.java constants (interface ae). GENERATED by tools/gen_ae.py - do not edit."""', ""]
    i = 0
    while i < len(lines):
        m = DECL.search(lines[i])
        if not m:
            i += 1
            continue
        start = i
        chunk = lines[i][m.end():]
        while not chunk.rstrip().endswith(";"):
            i += 1
            chunk += " " + lines[i].strip()
        value = convert(chunk.rstrip()[:-1].strip())
        value = re.sub(r"\s+", " ", value)
        res.append(f"# ae.java:{start + 1}-{i + 1}  ({m.group(1)})")
        name = m.group(2) + ("_" if keyword.iskeyword(m.group(2)) else "")  # Python keyword -> trailing _
        res.append(f"{name} = {value}")
        i += 1
    DST.write_text("\n".join(res) + "\n", encoding="utf-8")
    print("wrote", DST)


if __name__ == "__main__":
    main()
