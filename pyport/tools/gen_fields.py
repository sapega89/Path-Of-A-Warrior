"""Generate field declarations from Java classes (no hand typing of ~400 fields).

  pow/game/structs.py   - small data classes (h, z, n, ac, ...) with their fields and
                          the trivial constructors / reset methods
  pow/game/_ag_fields.py - class AgFields: every field of ag.java with its Java initial value

Usage: python pyport/tools/gen_fields.py
"""
import keyword
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "pyport" / "pow" / "game"

STRUCTS = ["h", "ac", "aa", "z", "p", "ai", "t", "ao", "o", "aj", "ad", "am", "ak", "w", "an",
           "y", "f", "i", "r", "a", "ah", "au", "ap", "n"]

FIELD = re.compile(r"^  ((?:(?:public|private|protected|static|final)\s+)*)([\w\[\]]+)\s+(\w+)\s*(?:=\s*(.*?))?;\s*$")
NEW_ARR = re.compile(r"new (\w+)((?:\[\w*\])+)$")
NEW_OBJ = re.compile(r"new (\w+)\((.*)\)$")
PRIM = {"int", "short", "byte", "long", "char", "float", "double"}


def py(name):
    return name + "_" if keyword.iskeyword(name) else name


def default(t):
    if t in PRIM:
        return "0"
    if t == "boolean":
        return "False"
    return "None"


def arr(base, dims):
    """new T[a][b][] -> nested Python lists"""
    sizes = re.findall(r"\[(\w*)\]", dims)
    def build(k):
        if k == len(sizes) or sizes[k] == "":
            return None
        inner = build(k + 1)
        if inner is None:
            leaf = default(base) if k == len(sizes) - 1 else "None"
            return f"[{leaf}] * {sizes[k]}" if k == len(sizes) - 1 else f"[None] * {sizes[k]}"
        return f"[{inner} for _ in range({sizes[k]})]"
    return build(0)


def value(t, init, known):
    if init is None:
        return default(t.rstrip("[]") if not t.endswith("]") else "Object") if not t.endswith("]") else "None"
    init = init.strip()
    m = NEW_ARR.match(init)
    if m:
        return arr(m.group(1), m.group(2))
    m = NEW_OBJ.match(init)
    if m:
        if m.group(1) not in known:
            return "None  # LATE-INIT: new %s(%s) - created in ag.py after the class" % (m.group(1), m.group(2))
        return f"{m.group(1)}({m.group(2)})"
    if init in ("true", "false"):
        return init.capitalize()
    if init == "null":
        return "None"
    return init.rstrip("L")


def fields(cls):
    res = []
    for n, line in enumerate((ROOT / f"{cls}.java").read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        m = FIELD.match(line)
        if m and "(" not in m.group(2):
            res.append((n, "static" in m.group(1), m.group(2), m.group(3), m.group(4)))
    return res


def ctor_body(cls):
    text = (ROOT / f"{cls}.java").read_text(encoding="utf-8", errors="replace")
    m = re.search(r"public %s\(\) \{\n(.*?)\n  \}" % cls, text, re.S)
    if not m:
        return []
    out = []
    for line in m.group(1).splitlines():
        line = line.strip().rstrip(";")
        line = re.sub(r"this\.", "self.", line)
        line = re.sub(r"new (\w+)\(\)", r"\1()", line)
        out.append(line)
    return out


def gen_structs():
    lines = ['"""Small Java data classes. GENERATED by tools/gen_fields.py - do not edit by hand."""', ""]
    for cls in STRUCTS:
        fl = fields(cls)
        args = ""
        ctor = ctor_body(cls)
        if cls == "ac":
            args = ", paramInt1=0, paramInt2=0, paramInt3=0, paramInt4=0"
            ctor = ["self.a = paramInt1", "self.b = paramInt2", "self.c = paramInt3", "self.d = paramInt4"]
        lines.append(f"class {cls}:  # {cls}.java")
        lines.append(f"    def __init__(self{args}):")
        for n, st, t, name, init in fl:
            lines.append(f"        self.{py(name)} = {value(t, init, STRUCTS)}  # {cls}.java:{n} {t}")
        for c in ctor:
            lines.append(f"        {c}  # constructor")
        if not fl and not ctor:
            lines.append("        pass")
        if cls in ("z",):
            lines += ["", "    def a(self):  # z.java:15-22",
                      "        self.a = 0", "        self.b = 0", "        self.c = 0", "        self.d = 0",
                      "        self.e = 0", "        self.f = 0"]
        if cls == "o":
            lines += ["", "    def a_v(self):  # o.java (final void a())", "        self.a = None"]
        if cls == "n":
            lines += ["", "    def a_v(self):  # n.java:130-144",
                      "        for b in range(9):", "            self.X[b] = z()",
                      "        for b in range(25):", "            self.Y[b] = z()",
                      "        for b in range(5):", "            self.Z[b] = p()",
                      "        for b in range(2):", "            self.a[b] = h()",
                      "        for b in range(2):", "            self.b[b] = h()",
                      "        self.j = h()", "        self.Q = h()"]
        lines.append("")
        lines.append("")
    (OUT / "structs.py").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def gen_ag():
    lines = ['"""All fields of ag.java with their initial values. GENERATED by tools/gen_fields.py."""',
             "from pow.game.structs import *  # noqa: F401,F403", "", "",
             "class AgFields:"]
    for n, st, t, name, init in fields("ag"):
        v = value(t, init, STRUCTS)
        if init and init.startswith("new Random"):
            v = "None"
        lines.append(f"    {py(name)} = {v}  # ag.java:{n} {'static ' if st else ''}{t}")
    (OUT / "_ag_fields.py").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    gen_structs()
    gen_ag()
    print("ok")
